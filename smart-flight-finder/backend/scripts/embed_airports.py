"""Write the airport catalog into the demo page, between the AIRPORT-TABLE markers.

    python -m scripts.embed_airports            # rewrite ../public/index.html
    python -m scripts.embed_airports --check    # exit 1 when the page is out of date (a test runs this)

The source of truth is ``app/data/airports.py`` (+ ``asia_airports.py``): the page gets the same codes, names, groups,
countries and gateway flags, plus the standard UTC offset of every airport (only used to place 航班待選 placeholder legs).
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from datetime import UTC, datetime
from pathlib import Path
from zoneinfo import ZoneInfo

from app.data.airports import BY_CODE, COUNTRY_ZH, GROUPS, TIMEZONES, TW_ORIGINS

PAGE = Path(__file__).resolve().parents[2] / "public" / "index.html"
START = "/* AIRPORT-TABLE:START"
END = "/* AIRPORT-TABLE:END */"
_BLOCK = re.compile(re.escape(START) + r".*?" + re.escape(END), re.DOTALL)


def utc_offset(code: str) -> str:
    """Standard-time offset such as ``+08:00`` (taken in January, the northern winter)."""

    off = datetime(2027, 1, 15, 12, tzinfo=UTC).astimezone(ZoneInfo(TIMEZONES[code])).utcoffset()
    minutes = int(off.total_seconds() // 60)
    sign = "+" if minutes >= 0 else "-"
    return f"{sign}{abs(minutes) // 60:02d}:{abs(minutes) % 60:02d}"


def block() -> str:
    order = {g: i for i, g in enumerate(GROUPS)}
    airports = sorted(BY_CODE.values(), key=lambda a: (order[a.group], list(BY_CODE).index(a.code)))
    rows = ",\n".join(
        "  " + json.dumps([a.code, a.name_zh, a.group, a.country, int(a.outstation)], ensure_ascii=False)
        for a in airports
    )
    offsets = json.dumps({a.code: utc_offset(a.code) for a in airports}, separators=(",", ":"))
    return f"""{START} (generated by scripts/embed_airports.py from app/data/airports.py — edit the catalog, not this block) */
const AIRPORTS = [
  // code, name, group, country, 外站 candidate?
{rows},
].map(([code, name, group, country, outstation]) => ({{ code, name, group, country, outstation: !!outstation }}));
const AIRPORT_BY_CODE = new Map(AIRPORTS.map(a => [a.code, a]));
const AIRPORT_GROUPS = {json.dumps(list(GROUPS), ensure_ascii=False)};
const COUNTRY_ZH = {json.dumps(COUNTRY_ZH, ensure_ascii=False, separators=(',', ':'))};
const COUNTRY = Object.fromEntries(AIRPORTS.filter(a => a.country !== 'TW').map(a => [a.code, a.country]));
const TW_AIRPORTS_LIST = {json.dumps([a.code for a in TW_ORIGINS])};
// Standard UTC offset of every airport — only used to place 航班待選 placeholder segments.
const UTC_OFFSET = {offsets};
{END}"""


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--page", type=Path, default=PAGE)
    args = ap.parse_args()
    html = args.page.read_text(encoding="utf-8")
    if not _BLOCK.search(html):
        sys.exit(f"no {START} … {END} block in {args.page}")
    new = _BLOCK.sub(lambda _m: block(), html, count=1)
    if args.check:
        if new != html:
            print("public/index.html airport table is out of date: run python -m scripts.embed_airports")
            return 1
        return 0
    args.page.write_text(new, encoding="utf-8")
    print(f"airport table written ({len(BY_CODE)} airports)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
